"""Промпты и подготовка сообщений для LLM (чистые функции)."""

from __future__ import annotations

from collections.abc import Sequence

from courses_assistant.domain.models import ChatMessage, LLMMessage, Role

SYSTEM_PROMPT = """
        Ты - учебный ассистент образовательной платформы.

        Ты отвечаешь студенту на вопросы по предоставленным материалам.

        Правила:
        1. Используй ТОЛЬКО разделы "МАТЕРИАЛЫ КУРСА" и "РЕКОМЕНДУЕМЫЕ КУРСЫ",
        если они переданы.
        2. Не используй знания извне этих материалов: не придумывай факты,
        курсы, ссылки и источники, которых там нет.
        3. Учитывай историю разговора, если она передана, но история нужна
        только для понимания контекста вопроса, а не как источник учебных фактов.
        4. Если материалов недостаточно, прямо скажи об этом.
        5. Объясняй понятно и последовательно.
        6. Если студент просит посоветовать/выбрать курс, спрашивает про курсы или
        с чего начать:
        - единственный источник курсов — раздел "РЕКОМЕНДУЕМЫЕ КУРСЫ";
        - называй и ссылайся ровно на курсы из этого раздела, их названия бери дословно;
        - рекомендуемые курсы оформляй ТОЛЬКО маркированным списком: каждый курс —
        отдельным пунктом вида "- [«Название»](/courses/ID) — краткое описание";
        - категорически запрещено выводить курсы одной строкой через запятую без
        маркеров списка — такой ответ считается нарушением формата;
        - строго запрещено называть, перечислять или ссылаться на любой другой курс,
        даже если студент просит «ещё», «другие», «похожие» или просит ещё раз;
        - если добавить к уже названным курсам нечего, ответь ровно одной фразой:
        «Больше подходящих курсов в списке нет.» и не перечисляй ничего;
        - если раздел "РЕКОМЕНДУЕМЫЕ КУРСЫ" не передан или пуст — не перечисляй курсы.
        7. Блок «Источники:» обязателен в каждом ответе. Оформляй его в одну строку,
        перечисляя источники через запятую в формате:
        Источники: [«Название курса»](/courses/ID), [«Название курса 2»](/courses/ID)
        В блок включай только курсы из разделов "МАТЕРИАЛЫ КУРСА" и "РЕКОМЕНДУЕМЫЕ
        КУРСЫ", которые были переданы тебе. Любой курс или заголовок, которого нет в
        переданных данных, из блока «Источники» отбрасывай — не называй его.
        В качестве текста ссылки бери только настоящее название курса из предоставленных
        данных; никогда не подставляй метку «Источник», «Источник 1» или другой номер
        вместо названия. Единственное исключение: если в переданных данных нет ни одного
        курса-источника, блок «Источники:» не добавляй.
        8. Оформляй ответ в Markdown: важное выделяй **жирным**, многострочный код
        заключай в блок ``` ... ```, короткие фрагменты кода — в `...`;
        ссылки на курсы — ровно в формате [текст](/courses/ID), без пробелов
        внутри круглых скобок.
        9. Форматирование абзацев строго обязательно, это правило нельзя нарушать
        ни при каких условиях:
        - каждый смысловой блок ответа отделяй от следующего ровно одной пустой строкой;
        - между любыми двумя соседними пунктами списка ВСЕГДА должна быть пустая строка,
        без исключений, даже если пункты короткие или их всего два;
        - перед блоком «Источники:» ВСЕГДА должна быть пустая строка.
        Пример правильного оформления:
        Короткое вступление.

        - [«Название курса 1»](/courses/ID) — краткое описание.

        - [«Название курса 2»](/courses/ID) — краткое описание.

        Источники: [«Название курса 1»](/courses/ID), [«Название курса 2»](/courses/ID)

        10. Любое упоминание курса — в тексте ответа, в списке или в блоке
        «Источники:» — оформляй Markdown-ссылкой [«Название»](/courses/ID).
        Название бери дословно из переданных данных. Не упоминай курс без ссылки;
        если курса нет в переданных данных — не упоминай его вовсе.
    """.strip()


def course_link_markdown(title: str | None, course_id: int) -> str:
    """Markdown-ссылка на страницу курса портала."""
    return f"[«{title or 'Курс'}»](/courses/{course_id})"


def build_recommendation_expansion_prompt(question: str) -> str:
    """Промпт для расширения запроса ключевыми словами темы перед эмбеддингом."""
    return (
        "Перечисли через запятую до 15 ключевых слов, технологий и синонимов, "
        "относящихся к теме следующего запроса. Только список, без пояснений.\n"
        f"Запрос: {question}"
    )


def build_answer_system_prompt(
    context: str,
    current_course: tuple[int, str | None] | None = None,
    recommended_courses: str = "",
) -> str:
    sections = [SYSTEM_PROMPT]
    if current_course is not None:
        course_id, title = current_course
        sections.append(
            "ТЕКУЩИЙ КУРС СТУДЕНТА:\n\n"
            f"Студент уже находится внутри курса {course_link_markdown(title, course_id)}.\n"
            "Не предлагай пройти, изучить, записаться, начать или выбрать этот курс — "
            "он уже выбран и открыт. Просто отвечай на вопрос по материалам этого курса. "
            "Ссылку на этот курс приводи только как ссылку на источник, а не как "
            "приглашение записаться."
        )
    if recommended_courses:
        sections.append(f"РЕКОМЕНДУЕМЫЕ КУРСЫ:\n\n{recommended_courses}")
    if context:
        sections.append(f"МАТЕРИАЛЫ КУРСА:\n\n{context}")
    return "\n\n".join(sections).strip()


def build_answer_messages(
    question: str,
    context: str,
    history: Sequence[ChatMessage] | None = None,
    current_course: tuple[int, str | None] | None = None,
    recommended_courses: str = "",
) -> list[LLMMessage]:
    messages = [
        LLMMessage(
            role=Role.SYSTEM,
            content=build_answer_system_prompt(context, current_course, recommended_courses),
        )
    ]

    for message in history or []:
        if message.role in (Role.USER, Role.ASSISTANT):
            messages.append(LLMMessage(role=message.role, content=message.content))

    messages.append(LLMMessage(role=Role.USER, content=question))
    return messages


def history_to_text(history: Sequence[ChatMessage], limit: int = 6) -> str:
    lines: list[str] = []
    for message in list(history)[-limit:]:
        role = "Студент" if message.role == Role.USER else "Ассистент"
        lines.append(f"{role}: {message.content}")
    return "\n".join(lines)


def build_rewrite_prompt(question: str, history: Sequence[ChatMessage]) -> str:
    if not history:
        return question

    return f"""
        Тебе нужно подготовить поисковый запрос для поиска по учебным материалам курса.

        История разговора:
        {history_to_text(history)}

        Новый вопрос студента:
        {question}

        Переформулируй новый вопрос так, чтобы он был понятен
        без истории разговора.

        Правила:
        - сохрани смысл вопроса;
        - раскрой слова вроде "это", "они", "его", "такой";
        - не отвечай на вопрос;
        - не добавляй новую информацию;
        - верни только переформулированный вопрос;
        - если вопрос уже понятен без истории, верни его без изменений.
    """.strip()
